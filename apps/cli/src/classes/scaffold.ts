/**
 * `factory class new`: write a task class that is red by construction.
 *
 * The scaffolder exists to make one property unavoidable: **a fresh class fails.** Every rule it writes is
 * a stub that exits 1, the visible check is a stub that prints a failing `FACTORY_SUMMARY`, and the
 * descriptor declares no visible rules and no mutation matrix. `factory class doctor` therefore refuses
 * the class on four counts before the author has written one line of real logic, and each refusal names a
 * sentence to write rather than a syntax to learn.
 *
 * What it deliberately does **not** do:
 *
 * - **It does not generate rules.** A rule is a claim about the defect a class exists to catch; a generator
 *   would produce plausible patterns with no defect behind them, which is how a corpus ends up measuring
 *   itself. The stubs say so in their own header.
 * - **It does not touch a repository.** The class's base revisions and repaired tree come from the operator
 *   (`--repo`, `--base`, `--repair` on the doctor), because a class whose farm was generated by the same
 *   tool that certifies it proves nothing about the farm.
 * - **It does not invent a mutation matrix.** The rows are the evidence that each rule can fail; the
 *   scaffolder writes an empty table and the doctor refuses until it is filled.
 *
 * The one thing it does compute is identity: the revision directory carries a hash of the sources it wrote
 * (so re-running with the same arguments rewrites the same revision, and a changed stub is a new revision),
 * and the manifest's `revisionHash` is the hash of the scenario list the loader will read back.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { contentHash } from '@factory/contracts';
import { hashableScenarios } from '@factory/wall';

import { CLASS_DESCRIPTOR_FILE } from './descriptor.ts';

export interface ScaffoldInput {
  readonly corpusRoot: string;
  readonly taskClass: string;
  /** One stub rule per id. Ids are written verbatim into `class.json` and the manifest. */
  readonly ruleIds: readonly string[];
  /** The command the wall will run as its own gate, e.g. `['node', 'tools/check-imports.mjs']`. */
  readonly visibleCheckArgv: readonly string[];
  /** Whether that command must print `FACTORY_SUMMARY`. Defaults to true (a pinned suite). */
  readonly requireSummary?: boolean;
  /** Fixed revision name; otherwise derived from the date and a hash of the written sources. */
  readonly revision?: string;
  /** Clock, for a deterministic name in tests. */
  readonly now?: Date;
}

export interface ScaffoldResult {
  readonly revision: string;
  readonly revisionHash: string;
  readonly directory: string;
  readonly files: readonly string[];
  /** The command that shows the class is red, quoted so the operator can paste it. */
  readonly doctorCommand: string;
}

const RULE_STUB = (ruleId: string): string =>
  `/**
 * Rule \`${ruleId}\`: a claim about a defect, and nothing else.
 *
 * This stub fails on purpose. A rule that starts green has never been observed failing, so a class built
 * from green rules certifies whatever passes them — which is everything.
 *
 * Shape (the wall runs this with the candidate tree as the working directory, and reads the exit code):
 *
 *   - exit 0 the candidate satisfies the rule;
 *   - exit 1 it does not, and the first line of output says where;
 *   - anything else is a rule that could not run, and the wall treats that as unknown.
 *
 * Write the pattern, then plant the defect it exists for in \`mutation-matrix.md\` and confirm this file
 * fails on it. If you cannot name a tree where it fails, the rule is not measuring anything yet.
 */
console.log('${ruleId}: not implemented — this rule is a stub and fails on purpose');
process.exit(1);
`;

const SUITE_STUB = (taskClass: string): string =>
  `/**
 * The visible check for \`${taskClass}\`: the one signal the worker is allowed to see.
 *
 * Two jobs, and the second is the one that is easy to forget:
 *
 * 1. enforce the subset of rules the class lets the worker see;
 * 2. print \`FACTORY_SUMMARY {"passed":n,"failed":n,"unknown":0,"exitCode":n}\`, because the wall reads that
 *    line rather than guessing from exit codes. Without it the suite is unknown — never a pass.
 *
 * This stub fails on purpose. Replace it with the real check, keep the summary line, and add its rule ids
 * to \`visibleRules\` in ${CLASS_DESCRIPTOR_FILE} — leaving at least one rule invisible, or the wall is a mirror.
 */
console.log('${taskClass}: visible check not implemented — this stub fails on purpose');
console.log('FACTORY_SUMMARY ' + JSON.stringify({ passed: 0, failed: 1, unknown: 0, exitCode: 1 }));
process.exit(1);
`;

function defaultRevisionName(taskClass: string, sourcesHash: string, now: Date): string {
  const date = now.toISOString().slice(0, 10);
  const time = now.toISOString().slice(11, 19).replaceAll(':', '');
  // `T` sorts after `-`, so a revision written today outranks any date-only revision of the same day —
  // the loader takes the greatest name, and a class that quietly loses that comparison is a class nobody
  // is measuring.
  return `h-${taskClass}-${date}T${time}-${sourcesHash.slice(0, 8)}`;
}

/** Compare two revision names the way the loader does (code units), returning the greatest. */
function greatestName(names: readonly string[]): string | null {
  let greatest: string | null = null;
  for (const name of names) if (greatest === null || name > greatest) greatest = name;
  return greatest;
}

export function scaffoldClass(input: ScaffoldInput): ScaffoldResult {
  const { corpusRoot, taskClass, ruleIds } = input;
  const requireSummary = input.requireSummary ?? true;
  const visibleCheckArgv = [...input.visibleCheckArgv];

  if (ruleIds.length === 0) throw new Error('a class needs at least one rule id');
  const uniqueRules = [...new Set(ruleIds)];
  if (uniqueRules.length !== ruleIds.length) throw new Error('rule ids must be unique');

  const classDir = join(corpusRoot, taskClass);
  mkdirSync(classDir, { recursive: true });

  const ruleSources = uniqueRules.map((id) => [id, RULE_STUB(id)] as const);
  const suiteSource = SUITE_STUB(taskClass);
  const sourcesHash = contentHash({
    rules: ruleSources.map(([id, source]) => ({ id, source })),
    suite: suiteSource,
    visibleCheckArgv,
  }).slice('sha256:'.length, 'sha256:'.length + 8);

  const revision =
    input.revision ?? defaultRevisionName(taskClass, sourcesHash, input.now ?? new Date());
  const existing = readdirSync(classDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);
  const greatest = greatestName(existing.filter((name) => name !== revision));
  if (greatest !== null && revision <= greatest) {
    throw new Error(
      `the revision name ${revision} would lose to ${greatest}: the loader reads the greatest name, so the ` +
        'class would be measured against the older corpus. Pass --revision with a name that sorts after it.',
    );
  }

  const directory = join(classDir, revision);
  mkdirSync(join(directory, 'rules'), { recursive: true });
  mkdirSync(join(directory, 'suite'), { recursive: true });

  const files: string[] = [];
  const rulePaths: string[] = [];
  for (const [id, source] of ruleSources) {
    const path = join(directory, 'rules', `${id}.mjs`);
    writeFileSync(path, source);
    files.push(path);
    rulePaths.push(path);
  }
  const suitePath = join(directory, 'suite', `${taskClass}-guard.mjs`);
  writeFileSync(suitePath, suiteSource);
  files.push(suitePath);

  const scenarios = uniqueRules.map((id, index) => ({
    id,
    taskClass,
    argv: ['node', rulePaths[index] ?? ''],
    expectExit: [0],
  }));
  const revisionHash = contentHash(hashableScenarios(scenarios));
  const manifestPath = join(directory, 'manifest.json');
  writeFileSync(
    manifestPath,
    `${JSON.stringify({ revision, taskClass, scenarios, revisionHash }, null, 2)}\n`,
  );
  files.push(manifestPath);

  const descriptor = {
    taskClass,
    visibleCheck: { argv: visibleCheckArgv, requireSummary },
    rules: uniqueRules,
    visibleRules: [],
    mutationMatrix: [],
  };
  const descriptorPath = join(directory, CLASS_DESCRIPTOR_FILE);
  writeFileSync(descriptorPath, `${JSON.stringify(descriptor, null, 2)}\n`);
  files.push(descriptorPath);

  const matrixPath = join(directory, 'mutation-matrix.md');
  writeFileSync(
    matrixPath,
    [
      `# Mutation matrix — ${taskClass}`,
      '',
      'Each row is a defect, planted in a copy of the repaired tree, that the named rules must catch. The',
      'doctor refuses the class until every rule appears in at least one row: a rule no defect reddens is a',
      'rule whose failure nobody has seen.',
      '',
      '| # | defect (what you change in the repaired tree) | rules that must fail |',
      '| --- | --- | --- |',
      ...uniqueRules.map((id, index) => `| ${String(index + 1)} | | \`${id}\` |`),
      '',
      'Then copy each row into `class.json` as `{ "defect": "…", "redRules": ["…"] }` and run the doctor with',
      'the planted trees as its bases.',
      '',
    ].join('\n'),
  );
  files.push(matrixPath);

  const readmePath = join(directory, 'README.md');
  writeFileSync(
    readmePath,
    [
      `# ${taskClass}, revision ${revision}`,
      '',
      'This class is **red by construction**: every rule is a stub that exits 1, the visible check exits 1, the',
      'descriptor declares no visible rules and no mutation matrix. That is the starting point, not a defect.',
      '',
      'To finish it:',
      '',
      '1. Write each rule in `rules/`. Run it against a tree that must fail and against the repaired tree.',
      '2. Fill `mutation-matrix.md` and copy the rows into `class.json`.',
      '3. Set `visibleRules` in `class.json` to the subset the visible check enforces — strictly smaller than',
      '   `rules`. Replace the suite stub with a real check that keeps the `FACTORY_SUMMARY` line.',
      '4. Run the doctor against the base revisions and the repaired tree:',
      '',
      '```',
      'factory class doctor --class ' + taskClass + ' --root ' + corpusRoot + ' \\',
      '  --repo <mirror.git> --base <sha> [--base <sha>…] --repair <repaired-tree>',
      '```',
      '',
      'The class is authored when the doctor exits 0. Certification is a separate, spending decision',
      '(`factory certify`, see `docs/runbooks/certify-class.md`).',
      '',
    ].join('\n'),
  );
  files.push(readmePath);

  const doctorCommand =
    `factory class doctor --class ${taskClass} --root ${corpusRoot} --repo <mirror.git> ` +
    `--base <sha> --repair <repaired-tree>`;

  return { revision, revisionHash, directory, files, doctorCommand };
}

/** Whether a path already holds a scaffolded revision (used by tests and by `class new --dry-run`). */
export function revisionDirExists(
  corpusRoot: string,
  taskClass: string,
  revision: string,
): boolean {
  return existsSync(join(corpusRoot, taskClass, revision, 'manifest.json'));
}

/** A short, stable digest of a file's bytes, for reporting what the scaffolder wrote. */
export function fileDigest(path: string): string {
  return createHash('sha256').update(`file:${path}`).digest('hex').slice(0, 12);
}
