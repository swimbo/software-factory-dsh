/**
 * The per-attempt DSH profile overlay — the one place that knows DSH YAML.
 *
 * DSH has no per-invocation flags for model, sandbox mode or approval policy
 * (`findings.md` D2). Everything an attempt needs is therefore expressed as a
 * patch-list overlay that `dsh --patch` applies *after* the profile layer, and
 * this file is the only place in the factory that writes that YAML. If a future
 * DSH renames a config row, this module breaks first and loudly.
 *
 * The five entries below are not a design preference — they are what
 * `dsh --dump-config` accepted with **no** `did not activate` warning, verified
 * against the installed binary in
 * `docs/planning/dark-factory-dsh/evidence/phase-9b-dsh-integration-probe.md`.
 * Emitting only `sandbox-policy` + `approval` (the obvious two) composes a
 * sandbox/approval pair that matches no named preset, so the permission service
 * throws, one entry fails to activate, and the run continues with **degraded
 * permission handling** — a silent failure, which is the worst kind for a dark
 * run. `permission-presets` is what makes the pair legal.
 *
 * Secrets: the overlay may name an environment variable, never carry its value.
 * `assertNoSecrets` is the guard, and it is deliberately blunt.
 */

import { join } from 'node:path';

/** The two trust domains that get their own `DSH_HOME`. See {@link buildDshHome}. */
export const DSH_HOMES = ['worker', 'evaluator'] as const;
export type DshDomain = (typeof DSH_HOMES)[number];

/**
 * Compaction policy. `'none'` disables automatic conversation compaction.
 *
 * This is not cosmetic. `compaction-basic` summarises with the *session's* own
 * provider and model (`packages/compaction/compaction-basic/src/index.ts`
 * resolves `summarizationProvider`/`summarizationModel` from the request
 * header), so leaving it on means the harness spends proxied inference requests
 * the admission budget never reserved — and the receipt's tool-call record goes
 * incomplete, because compaction drops older tool results from the surface.
 * Off is the honest setting for a factory that must account for every request
 * and be able to explain its own logs.
 */
export type Compression = 'none' | 'auto';

export interface OverlayInput {
  /**
   * The sandbox root: the attempt's own clone, and the path the container mounts
   * at the *same* absolute path. One path, not two — DSH keys its session log by
   * the process cwd and `--session-id` adoption refuses when the cwd differs, so
   * "the sandbox root" and "where the process runs" must be one string.
   */
  attemptDir: string;
  /** The credential proxy's Anthropic-compatible base URL. Never the gateway's. */
  proxyBaseUrl: string;
  /** The per-role model id the proxy routes on, e.g. `factory-worker-tier`. */
  modelId: string;
  /** Env var *name* the provider resolves its key from. A name, never a value. */
  apiKeyEnv?: string;
  /**
   * The provider API shape the proxy speaks. Defaults to `'anthropic-messages'`, which is what
   * every existing overlay was built for; a Bifrost gateway that only speaks
   * OpenAI-completions asks for `'openai-completions'`. Authentication stays `apiKeyEnv` in
   * both cases: the gateway accepts `Authorization: Bearer <key>`, so no header plumbing.
   */
  api?: 'anthropic-messages' | 'openai-completions';
  /** Defaults to `'none'`. See {@link Compression}. */
  compression?: Compression;
}

/** The provider id the proxy is registered under inside DSH. */
const PROVIDER = 'bifrost';
/** The preset name the sandbox+approval pair is declared as. */
const PRESET = 'factory-worker';

/**
 * A YAML scalar that round-trips to the exact string given.
 *
 * Bare only when it is unambiguously a string: an id like `1017` or `no` must be
 * quoted or YAML reads it as a number/boolean, and a model id that silently
 * becomes an integer is the sort of bug that costs a paid trial to find.
 */
function scalar(value: string): string {
  const bareSafe = /^[A-Za-z0-9_][A-Za-z0-9_.-]*$/.test(value);
  const looksTyped =
    /^(?:true|false|yes|no|on|off|null|~|[-+]?(?:\d[\d_]*\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)$/i.test(
      value,
    );
  if (bareSafe && !looksTyped) return value;
  return `'${value.replaceAll("'", "''")}'`;
}

/**
 * Build the overlay YAML for one attempt.
 *
 * Pure and total: no I/O, no clock, no randomness, so the same input always
 * produces byte-identical YAML and a receipt can name the overlay by hash.
 */
export function buildOverlay(input: OverlayInput): string {
  const apiKeyEnv = input.apiKeyEnv ?? 'BIFROST_API_KEY';
  const api = input.api ?? 'anthropic-messages';
  const compression = input.compression ?? 'none';
  const lines: string[] = [
    '# Generated by the factory for one attempt. Not for editing, not for committing.',
    '# Provider, model, sandbox mode and approval policy are all decided here because',
    '# DSH has no per-invocation flags for any of them.',
    '- id: sandbox-policy',
    "  name: '@deepseek-ai/dsh-sandbox-policy'",
    '  config:',
    '    mode: workspace-write',
    `    workspaceRoot: ${scalar(input.attemptDir)}`,
    '- id: approval',
    "  name: '@deepseek-ai/dsh-user-approval'",
    '  config:',
    // A headless run cannot answer an approval prompt, so `ask` fails closed and
    // the attempt stalls. `never` plus the workspace-write sandbox is the only
    // pairing a dark attempt can use.
    '    policy: never',
    '- id: permission',
    "  name: '@deepseek-ai/dsh-permission-presets'",
    '  config:',
    `    defaultPreset: ${PRESET}`,
    '    presets:',
    `      ${PRESET}:`,
    '        sandbox: workspace-write',
    '        approval: never',
    '- id: llm-pi-ai',
    "  name: '@deepseek-ai/dsh-llm-pi-ai'",
    '  config:',
    '    providers:',
    `      ${PROVIDER}:`,
    '        displayName: Bifrost (factory proxy)',
    // The value is the *name*. The proxy holds the key and injects it, so the
    // worker process never has a credential to leak into a log or a diff.
    `        apiKeyEnv: ${apiKeyEnv}`,
    `        api: ${api}`,
    `        baseURL: ${scalar(input.proxyBaseUrl)}`,
    '        models:',
    `          - id: ${scalar(input.modelId)}`,
    '            name: Factory worker tier',
    '- id: agent-default-model',
    "  name: '@deepseek-ai/dsh-agent-default-model'",
    '  config:',
    `    provider: ${PROVIDER}`,
    `    model: ${scalar(input.modelId)}`,
  ];
  if (compression === 'none') {
    lines.push(
      '- id: compaction-basic',
      "  name: '@deepseek-ai/dsh-compaction-basic'",
      '  config:',
      '    auto: false',
    );
  }
  const overlay = `${lines.join('\n')}\n`;
  assertNoSecrets(overlay);
  return overlay;
}

/**
 * Refusals for anything that looks like it carries a secret *value*.
 *
 * Two shapes are checked because they fail differently: a raw token pasted into
 * a field, and an env-var *assignment* (`NAME=value`) that would leak through
 * the process environment the overlay is loaded beside. A bare `apiKeyEnv: NAME`
 * is the only credential-shaped thing an overlay may contain.
 */
const SECRET_PATTERNS: readonly { readonly name: string; readonly re: RegExp }[] = [
  // `sk-` is Anthropic/OpenAI's key prefix; `sk-ant-`, `sk-proj-` fall under it.
  { name: 'a sk- prefixed API key', re: /\bsk-[A-Za-z0-9_-]{8,}/ },
  // `NAME=value` for anything credential-shaped, including the one var we name.
  {
    name: 'a credential assignment (NAME=value)',
    re: /[A-Z0-9_]*(?:API_KEY|APIKEY|TOKEN|SECRET|PASSWORD|CREDENTIAL)[A-Z0-9_]*\s*=\s*\S/,
  },
  // A YAML pair naming a credential field with a non-empty, non-null value.
  {
    name: 'a credential field with a value',
    re: /^\s*(?:apiKey|api_key|token|secret|password|credential|passphrase)\s*:\s*(?!['"]?(?:null|~|''|"")\s*$)['"]?\S/m,
  },
  // A private key block.
  { name: 'a private key block', re: /-----BEGIN [A-Z ]*PRIVATE KEY-----/ },
];

/**
 * Throw if `overlay` contains anything that looks like a secret value.
 *
 * Called by {@link buildOverlay} itself, so an overlay that never passes this
 * cannot be written to disk by a caller who forgot. The error message names the
 * *shape* that matched and never echoes the matched text — an error log is one
 * of the places a leaked key ends up.
 */
export function assertNoSecrets(overlay: string): void {
  for (const { name, re } of SECRET_PATTERNS) {
    const match = re.exec(overlay);
    if (match === null) continue;
    // Report the line number and the shape only. Never the value.
    const offset = match.index;
    const line = overlay.slice(0, offset).split('\n').length;
    throw new Error(
      `overlay refused: line ${String(line)} looks like ${name}; ` +
        'an overlay may name a credential environment variable but never carry its value',
    );
  }
}

/**
 * The `DSH_HOME` for one trust domain.
 *
 * One home per domain is what keeps the operator's home patch layer — MCP
 * servers, third-party plugins, personal model credentials — out of factory
 * runs. DSH composes `$DSH_HOME/cordis.patch.yml` into *every* profile, so a
 * worker sharing the operator's home would inherit the operator's Gmail and
 * calendar MCP servers (observed in Phase-5 research) and their credentials.
 * A fresh home has no patch layer at all, which the integration test asserts.
 * The wall gets a *different* home so a worker cannot reach evaluator
 * credentials even if it escapes its own sandbox.
 *
 * This is the **provisioned template**, not a runtime home: an attempt gets its
 * own home seeded from here and destroyed afterwards (`home.ts`, amendment A3.4).
 * A runtime `DSH_HOME` shared by every attempt would let attempt N configure
 * attempt N+1 through that same home patch layer.
 */
export function buildDshHome(root: string, domain: DshDomain): string {
  if (!DSH_HOMES.includes(domain)) {
    throw new Error(`unknown DSH trust domain: ${String(domain)}`);
  }
  // Root-relative and deterministic: the path appears in receipts and logs, so it
  // must not depend on the caller's cwd or on `~` expansion.
  return join(root, 'dsh-home', domain);
}
